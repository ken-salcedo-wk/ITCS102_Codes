#Arithmetic Operation
# + - Addition
# - - Subtraction
# * - Multiplication
# / - Division
# // - floor division
# ** - exponentation
# % - modulus

a = 20
b = 5

sum = a + b
difference = a - b
product = a * b
quotient = a / b
floordiv = a // b
exponentation = a ** b
modulus = a % b

print("The sum of ",a," and",b," is ",sum)
print("The difference of ",a," and",b," is ",difference)
print("The product of ",a," and",b," is ",product)
print("The quotient of ",a," and",b," is ",quotient)
print("The floor division of ",a," and",b," is ",floordiv)
print("The exponentation of ",a," and",b," is ",exponentation)
print("The modulus of ",a," and",b," is ",modulus)